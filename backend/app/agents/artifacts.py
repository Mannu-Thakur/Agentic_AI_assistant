"""
app/agents/artifacts.py — Workspace Artifact Management

Tracks all files produced by agents (generated code, PPTX, DOCX, CSV,
images, research reports) in a persistent in-memory + filesystem store.

Each artifact has a unique ID, type, path, creating agent, size, and
download URL.  An HTTP endpoint serves downloads; the frontend Workspace
panel lists artifacts per session/user.

Artifact types
--------------
  code      — Python / JS / shell scripts generated by CodeAgent
  pptx      — PowerPoint files from DocumentAgent
  docx      — Word documents from DocumentAgent
  pdf       — PDF reports from DocumentAgent
  csv       — Data files from DataAnalysisAgent
  image     — Images from VisionAgent or generated via DALL-E / Gemini
  report    — Markdown research reports from WebResearchAgent
  notebook  — Jupyter notebooks from DataAnalysisAgent
"""

from __future__ import annotations

import json
import logging
import asyncio
import os
import re
from dataclasses import dataclass, field, asdict
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional
from uuid import uuid4

from app.core.config import settings

logger = logging.getLogger("agents.artifacts")

_SAFE_COMPONENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$")
_SAFE_FILENAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,191}$")


# ─────────────────────────────────────────────────────────────────────────────
#  Data model
# ─────────────────────────────────────────────────────────────────────────────

ARTIFACT_TYPES = {
    "code":     {"ext": ".py",   "mime": "text/x-python"},
    "pptx":     {"ext": ".pptx", "mime": "application/vnd.openxmlformats-officedocument.presentationml.presentation"},
    "docx":     {"ext": ".docx", "mime": "application/vnd.openxmlformats-officedocument.wordprocessingml.document"},
    "pdf":      {"ext": ".pdf",  "mime": "application/pdf"},
    "csv":      {"ext": ".csv",  "mime": "text/csv"},
    "image":    {"ext": ".png",  "mime": "image/png"},
    "report":   {"ext": ".md",   "mime": "text/markdown"},
    "notebook": {"ext": ".ipynb","mime": "application/json"},
    "text":     {"ext": ".txt",  "mime": "text/plain"},
    "json":     {"ext": ".json", "mime": "application/json"},
}


@dataclass
class Artifact:
    """Represents a single workspace artifact produced by an agent."""
    id: str = field(default_factory=lambda: str(uuid4()))
    type: str = "text"                   # one of ARTIFACT_TYPES keys
    filename: str = ""
    path: str = ""                       # absolute filesystem path
    agent: str = ""                      # agent that created it
    user_id: str = ""
    session_id: str = ""                 # chat_id / mission_id
    size_bytes: int = 0
    created_at: str = field(
        default_factory=lambda: datetime.utcnow().isoformat()
    )
    description: str = ""
    download_url: str = ""               # /api/v1/artifacts/{id}/download
    metadata: Dict[str, Any] = field(default_factory=dict)
    preview: Optional[str] = None        # short text preview (first 500 chars)

    def to_dict(self) -> Dict[str, Any]:
        """Public metadata.  Never disclose the server filesystem layout."""
        data = asdict(self)
        data.pop("path", None)
        return data

    def to_index_dict(self) -> Dict[str, Any]:
        """Internal durable representation, including the verified disk path."""
        return asdict(self)

    @property
    def mime_type(self) -> str:
        return ARTIFACT_TYPES.get(self.type, {}).get("mime", "application/octet-stream")


# ─────────────────────────────────────────────────────────────────────────────
#  Artifact Store
# ─────────────────────────────────────────────────────────────────────────────

class ArtifactStore:
    """
    In-memory artifact index backed by filesystem storage.

    All writes are serialized through asyncio.Lock to prevent race conditions
    during parallel multi-agent execution.

    API
    ---
    store   = ArtifactStore()
    art     = await store.create(type, content_bytes, agent, user_id, session_id)
    arts    = store.list_by_session(session_id)
    art     = store.get(artifact_id)
    path    = store.get_path(artifact_id)
    deleted = await store.delete(artifact_id)
    """

    def __init__(self, base_dir: Optional[Path | str] = None) -> None:
        self._index: Dict[str, Artifact] = {}
        self._lock = asyncio.Lock()
        configured_base = base_dir if base_dir is not None else settings.ARTIFACT_DIR
        self._base = Path(configured_base).expanduser().resolve()
        self._base.mkdir(parents=True, exist_ok=True)
        self._load_index()

    # ── Persistence ──────────────────────────────────────────────────────────

    def _index_path(self) -> Path:
        return self._base / ".index.json"

    @staticmethod
    def _validate_component(value: str, label: str) -> str:
        if not _SAFE_COMPONENT.fullmatch(value or ""):
            raise ValueError(f"Invalid artifact {label}")
        return value

    @staticmethod
    def _validate_filename(filename: str) -> str:
        # A filename is not a path.  Reject traversal and Windows drive syntax
        # before normalising human-readable document titles to a safe filename.
        if (
            not filename
            or Path(filename).name != filename
            or "/" in filename
            or "\\" in filename
            or filename in {".", ".."}
            or filename.startswith(".")
            or "\x00" in filename
        ):
            raise ValueError("Invalid artifact filename")
        safe = re.sub(r"[^A-Za-z0-9._-]", "_", filename).strip("._")
        if not safe or not _SAFE_FILENAME.fullmatch(safe):
            raise ValueError("Invalid artifact filename")
        return safe

    def _path_under_base(self, *parts: str) -> Path:
        path = self._base.joinpath(*parts).resolve()
        try:
            path.relative_to(self._base)
        except ValueError as exc:
            raise ValueError("Artifact path escapes its storage directory") from exc
        return path

    def _load_index(self) -> None:
        """Load persisted artifact index on startup."""
        idx_path = self._index_path()
        if idx_path.exists():
            try:
                data = json.loads(idx_path.read_text())
                for item in data:
                    art = Artifact(**item)
                    self._validate_component(art.user_id, "owner")
                    self._validate_component(art.session_id, "session")
                    self._validate_filename(art.filename)
                    expected_path = self._path_under_base(
                        art.user_id, art.session_id, art.filename
                    )
                    # Do not trust an old/corrupted index path.  An item is
                    # accepted only when it resolves to its expected tenant path.
                    if art.path and Path(art.path).resolve() == expected_path and expected_path.is_file():
                        self._index[art.id] = art
                logger.info(f"[ArtifactStore] Loaded {len(self._index)} artifact(s) from index.")
            except Exception as e:
                logger.warning(f"[ArtifactStore] Could not load index: {e}")

    async def _save_index(self) -> None:
        """Persist the index to disk (called after mutations)."""
        try:
            data = [art.to_index_dict() for art in self._index.values()]
            index_path = self._index_path()
            temp_path = index_path.with_suffix(".tmp")
            temp_path.write_text(json.dumps(data, indent=2), encoding="utf-8")
            os.replace(temp_path, index_path)
        except Exception as e:
            logger.warning(f"[ArtifactStore] Could not save index: {e}")

    # ── Write ─────────────────────────────────────────────────────────────────

    async def create(
        self,
        artifact_type: str,
        content: bytes | str,
        agent: str,
        user_id: str,
        session_id: str,
        filename: Optional[str] = None,
        description: str = "",
        metadata: Optional[Dict] = None,
    ) -> Artifact:
        """
        Persist `content` to disk and register the artifact.

        Returns the newly created Artifact object.
        """
        if artifact_type not in ARTIFACT_TYPES:
            raise ValueError(f"Unsupported artifact type: {artifact_type}")
        user_id = self._validate_component(user_id, "owner")
        session_id = self._validate_component(session_id, "session")
        content_bytes = content.encode("utf-8") if isinstance(content, str) else content
        max_bytes = settings.MAX_ARTIFACT_SIZE_MB * 1024 * 1024
        if len(content_bytes) > max_bytes:
            raise ValueError(
                f"Artifact exceeds the {settings.MAX_ARTIFACT_SIZE_MB} MB size limit"
            )

        async with self._lock:
            art_id = str(uuid4())
            ext = ARTIFACT_TYPES[artifact_type]["ext"]
            safe_filename = self._validate_filename(
                filename or f"{artifact_type}_{art_id[:8]}{ext}"
            )

            # Store under user_id/session_id subdirectory
            subdir = self._path_under_base(user_id, session_id)
            subdir.mkdir(parents=True, exist_ok=True)
            file_path = self._path_under_base(user_id, session_id, safe_filename)

            # Write bytes or text
            if isinstance(content, str):
                file_path.write_text(content, encoding="utf-8")
            else:
                file_path.write_bytes(content)

            size = file_path.stat().st_size

            # Build preview for text-based artifacts
            preview: Optional[str] = None
            if artifact_type in ("code", "report", "text", "json", "csv"):
                try:
                    preview = file_path.read_text(encoding="utf-8", errors="replace")[:500]
                except Exception:
                    pass

            artifact = Artifact(
                id=art_id,
                type=artifact_type,
                filename=safe_filename,
                path=str(file_path.resolve()),
                agent=agent,
                user_id=user_id,
                session_id=session_id,
                size_bytes=size,
                description=description,
                download_url=f"/api/v1/artifacts/{art_id}/download",
                metadata=metadata or {},
                preview=preview,
            )
            self._index[art_id] = artifact
            await self._save_index()
            logger.info(
                f"[ArtifactStore] Created artifact {art_id} "
                f"type={artifact_type} agent={agent} size={size}B"
            )
            return artifact

    # ── Read ──────────────────────────────────────────────────────────────────

    def get(self, artifact_id: str) -> Optional[Artifact]:
        return self._index.get(artifact_id)

    def get_path(self, artifact_id: str) -> Optional[Path]:
        art = self._index.get(artifact_id)
        if art and art.path:
            try:
                p = self._path_under_base(art.user_id, art.session_id, art.filename)
            except ValueError:
                return None
            if p.is_file() and p.resolve() == Path(art.path).resolve():
                return p
        return None

    def list_by_session(self, session_id: str) -> List[Artifact]:
        return [
            art for art in self._index.values()
            if art.session_id == session_id
        ]

    def list_by_user(self, user_id: str) -> List[Artifact]:
        return [
            art for art in self._index.values()
            if art.user_id == user_id
        ]

    def list_by_type(self, artifact_type: str) -> List[Artifact]:
        return [
            art for art in self._index.values()
            if art.type == artifact_type
        ]

    # ── Delete ────────────────────────────────────────────────────────────────

    async def delete(self, artifact_id: str) -> bool:
        async with self._lock:
            art = self._index.get(artifact_id)
            if not art:
                return False
            file_path: Optional[Path] = None
            try:
                candidate = self._path_under_base(art.user_id, art.session_id, art.filename)
                if candidate.is_file() and art.path and candidate.resolve() == Path(art.path).resolve():
                    file_path = candidate
            except (OSError, ValueError):
                file_path = None
            self._index.pop(artifact_id, None)
            if file_path:
                try:
                    file_path.unlink(missing_ok=True)
                except Exception as e:
                    logger.warning(f"[ArtifactStore] Could not delete file: {e}")
            await self._save_index()
            return True

    def stats(self) -> Dict[str, Any]:
        return self._stats_for(self._index.values())

    def stats_for_user(self, user_id: str) -> Dict[str, Any]:
        """Return aggregate data only for the requesting tenant."""
        return self._stats_for(self.list_by_user(user_id))

    @staticmethod
    def _stats_for(artifacts: Any) -> Dict[str, Any]:
        artifacts = list(artifacts)
        total_size = sum(a.size_bytes for a in artifacts)
        by_type: Dict[str, int] = {}
        for art in artifacts:
            by_type[art.type] = by_type.get(art.type, 0) + 1
        return {
            "total_artifacts": len(artifacts),
            "total_size_bytes": total_size,
            "by_type": by_type,
        }


# Module-level singleton
artifact_store = ArtifactStore()
