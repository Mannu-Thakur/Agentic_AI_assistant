"""
app/agents/document_agent.py — Document / Presentation Generation Agent

Capabilities
------------
  • PowerPoint generation (PPTX) via python-pptx
  • Word document generation (DOCX) via python-docx
  • Markdown → structured content via LLM
  • Slide/section decomposition and layout selection
  • Artifact export to ArtifactStore

task_input keys
---------------
  query        : str   — Document title / topic / description
  doc_type     : str   — "pptx" | "docx" | "report" (default "pptx")
  sections     : list  — Optional pre-defined section list
  user_id      : str
  session_id   : str
  active_model : str
  api_keys     : dict
"""

from __future__ import annotations

import io
import json
import logging
import re
from typing import Any, Dict, List, Optional

from app.agents.registry import BaseAgent, AgentResult, agent_registry
from app.agents.artifacts import artifact_store
from app.agents.node_helpers import call_llm_json, call_llm_simple

logger = logging.getLogger("agents.document")


_NUMBER_WORDS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5,
    "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
}


def _requested_slide_count(query: str) -> Optional[int]:
    """Read an explicit total slide count, including common number words."""
    match = re.search(
        r"\b(\d+|one|two|three|four|five|six|seven|eight|nine|ten)\s*[- ]?slides?\b",
        query,
        re.IGNORECASE,
    )
    if not match:
        return None
    raw_count = match.group(1).lower()
    count = int(raw_count) if raw_count.isdigit() else _NUMBER_WORDS[raw_count]
    return max(1, count)


# ─────────────────────────────────────────────────────────────────────────────
#  PPTX Builder
# ─────────────────────────────────────────────────────────────────────────────

def _build_pptx(title: str, slides: List[Dict[str, Any]]) -> bytes:
    """
    Build a PowerPoint file from a slide list.
    Each slide: {title: str, bullets: list[str], notes: str}
    Returns bytes of the .pptx file.
    """
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    from pptx.enum.text import PP_ALIGN

    prs = Presentation()
    prs.slide_width  = Inches(13.33)
    prs.slide_height = Inches(7.5)

    # ── Title slide ──────────────────────────────────────────────────────────
    title_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_layout)
    slide.shapes.title.text = title
    if len(slide.placeholders) > 1:
        slide.placeholders[1].text = "Generated by Multi-Agent AI Workspace"

    # ── Content slides ────────────────────────────────────────────────────────
    content_layout = prs.slide_layouts[1]   # Title and Content layout
    for s in slides:
        sl = prs.slides.add_slide(content_layout)
        sl.shapes.title.text = s.get("title", "")

        tf = sl.placeholders[1].text_frame
        tf.clear()
        bullets = s.get("bullets", [])
        for i, bullet in enumerate(bullets[:8]):
            p = tf.add_paragraph() if i > 0 else tf.paragraphs[0]
            p.text = bullet
            p.level = 0
            p.font.size = Pt(18)

        # Add speaker notes
        notes = s.get("notes", "")
        if notes:
            notes_slide = sl.notes_slide
            notes_slide.notes_text_frame.text = notes

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


# ─────────────────────────────────────────────────────────────────────────────
#  DOCX Builder
# ─────────────────────────────────────────────────────────────────────────────

def _build_docx(title: str, sections: List[Dict[str, Any]]) -> bytes:
    """
    Build a Word document from a section list.
    Each section: {heading: str, content: str}
    Returns bytes of the .docx file.
    """
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.add_heading(title, level=0)

    for sec in sections:
        doc.add_heading(sec.get("heading", ""), level=1)
        content = sec.get("content", "")
        if content:
            doc.add_paragraph(content)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# ─────────────────────────────────────────────────────────────────────────────
#  Document Agent
# ─────────────────────────────────────────────────────────────────────────────

@agent_registry.register("document")
class DocumentAgent(BaseAgent):
    """
    Generates structured PowerPoint or Word documents from a topic/description
    using LLM-driven content planning and python-pptx/python-docx rendering.
    """

    name = "document"
    description = (
        "Generates PowerPoint presentations (PPTX) or Word documents (DOCX) "
        "from a topic or description. Uses LLM to plan structure and content, "
        "then renders professional documents as downloadable artifacts."
    )
    capabilities = [
        "pptx_generation", "docx_generation", "presentation",
        "document_creation", "report_generation",
    ]

    async def run(
        self,
        task_input: Dict[str, Any],
        config: Optional[Dict[str, Any]] = None,
    ) -> AgentResult:
        query      = task_input.get("query", "")
        doc_type   = task_input.get("doc_type", "pptx")
        user_id    = task_input.get("user_id", "anon")
        session_id = task_input.get("session_id", "default")
        from app.core.config import settings
        model      = task_input.get("active_model", settings.GEMINI_MODEL)
        api_keys   = task_input.get("api_keys", {})

        logger.info(f"[DocumentAgent] type={doc_type} query={query[:60]!r}")

        # ── Step 1: Plan structure via LLM ────────────────────────────────────
        if doc_type == "pptx":
            total_slide_count = _requested_slide_count(query)
            slide_count_instruction = (
                f"Create exactly {total_slide_count - 1} content slides because the rendered "
                f"deck includes one title slide for {total_slide_count} slides total."
                if total_slide_count else
                "Include 6-10 content slides plus a title slide."
            )
            plan_prompt = (
                f"Create a structured PowerPoint presentation plan for: {query}\n\n"
                "Respond with JSON:\n"
                '{"title": "...", "slides": [{"title": "...", "bullets": ["...", "..."], "notes": "..."}, ...]}\n'
                f"{slide_count_instruction} Use 3-5 concise bullet points per content slide. "
                "Be specific and informative."
            )
        else:
            plan_prompt = (
                f"Create a structured Word document plan for: {query}\n\n"
                "Respond with JSON:\n"
                '{"title": "...", "sections": [{"heading": "...", "content": "..."}, ...]}\n'
                "Include 5-8 sections with detailed content for each."
            )

        plan: Dict[str, Any] = {}
        try:
            plan = await call_llm_json(
                prompt=plan_prompt,
                model=model,
                api_keys=api_keys,
                system="You are an expert document planner. Output only valid JSON.",
                temperature=0.4,
            )
        except Exception as exc:
            logger.error(f"[DocumentAgent] Planning failed: {exc}")
            return AgentResult(
                agent_name=self.name,
                success=False,
                error=f"Document planning failed: {exc}",
            )

        if not isinstance(plan, dict) or not plan:
            return AgentResult(
                agent_name=self.name,
                success=False,
                error="LLM returned empty plan",
            )

        if doc_type == "pptx" and total_slide_count:
            expected_content_slides = total_slide_count - 1
            planned_slides = plan.get("slides", [])
            if not isinstance(planned_slides, list):
                planned_slides = []
            planned_slides = [slide for slide in planned_slides if isinstance(slide, dict)]

            if len(planned_slides) < expected_content_slides:
                repair_prompt = (
                    f"Repair this PowerPoint plan for the request: {query}\n\n"
                    f"The rendered deck must contain exactly {total_slide_count} slides total, "
                    f"including one title slide, so return exactly {expected_content_slides} "
                    "content slides. Keep and improve the supplied content, adding any missing "
                    "content slides needed to reach the exact total. Return the same JSON schema.\n\n"
                    f"Current draft:\n{json.dumps(plan, ensure_ascii=False)}"
                )
                try:
                    repaired_plan = await call_llm_json(
                        prompt=repair_prompt,
                        model=model,
                        api_keys=api_keys,
                        system="You are an expert document planner. Output only valid JSON.",
                        temperature=0.4,
                    )
                except Exception as exc:
                    logger.error(f"[DocumentAgent] Slide-count repair failed: {exc}")
                    return AgentResult(
                        agent_name=self.name,
                        success=False,
                        error=f"Could not complete the requested {total_slide_count}-slide deck: {exc}",
                    )

                if isinstance(repaired_plan, dict):
                    plan = repaired_plan
                    repaired_slides = plan.get("slides", [])
                    planned_slides = (
                        [slide for slide in repaired_slides if isinstance(slide, dict)]
                        if isinstance(repaired_slides, list) else []
                    )

            if len(planned_slides) < expected_content_slides:
                return AgentResult(
                    agent_name=self.name,
                    success=False,
                    error=(
                        f"Requested {total_slide_count} total slides, but the presentation plan "
                        f"contained only {len(planned_slides) + 1} after one repair attempt. "
                        "No incomplete deck was exported."
                    ),
                )

            plan["slides"] = planned_slides[:expected_content_slides]

        doc_title = plan.get("title", query[:60])

        # ── Step 2: Render document ────────────────────────────────────────────
        artifact_info: Optional[Dict] = None
        content_summary = ""

        try:
            if doc_type == "pptx":
                slides = plan.get("slides", [])
                if total_slide_count:
                    slides = slides[:total_slide_count - 1]
                doc_bytes = _build_pptx(doc_title, slides)
                filename  = f"{doc_title[:40].replace(' ', '_')}.pptx"
                art_type  = "pptx"
                content_summary = (
                    f"📊 **PowerPoint Presentation: {doc_title}**\n\n"
                    f"Generated **{len(slides) + 1} slides**:\n" +
                    "\n".join(f"- {s.get('title', '')}" for s in slides[:8])
                )
            else:
                sections = plan.get("sections", [])
                doc_bytes = _build_docx(doc_title, sections)
                filename  = f"{doc_title[:40].replace(' ', '_')}.docx"
                art_type  = "docx"
                content_summary = (
                    f"📄 **Word Document: {doc_title}**\n\n"
                    f"Generated **{len(sections)} sections**:\n" +
                    "\n".join(f"- {s.get('heading', '')}" for s in sections[:8])
                )

            art = await artifact_store.create(
                artifact_type=art_type,
                content=doc_bytes,
                agent=self.name,
                user_id=user_id,
                session_id=session_id,
                filename=filename,
                description=query[:120],
                metadata={"title": doc_title, "doc_type": doc_type},
            )
            artifact_info = art.to_dict()
            content_summary += (
                f"\n\n✅ **Download:** [{filename}]({art.download_url})"
            )

        except ImportError as exc:
            # python-pptx / python-docx not installed
            return AgentResult(
                agent_name=self.name,
                success=False,
                error=f"Document library not available: {exc}. Ensure python-pptx and python-docx are installed.",
            )
        except Exception as exc:
            logger.error(f"[DocumentAgent] Rendering failed: {exc}")
            return AgentResult(
                agent_name=self.name,
                success=False,
                error=f"Document rendering failed: {exc}",
            )

        return AgentResult(
            agent_name=self.name,
            success=True,
            content=content_summary,
            artifacts=[artifact_info] if artifact_info else [],
            metadata={
                "doc_type":   doc_type,
                "title":      doc_title,
                "filename":   filename,
                "slide_count": len(slides) + 1 if doc_type == "pptx" else 0,
                "section_count": len(plan.get("sections", [])) if doc_type != "pptx" else 0,
            },
        )
